"""P8a_rewrite_front.py — 重写摘要（结构化 250-350 词）、关键词、引言（4 段逻辑）"""
import re, json, io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

MD = r"D:\projects\OS_matrix_dualKO\manuscript\OS_manuscript_v1_cn.md"
CMAP = json.load(open(r"D:\projects\OS_matrix_dualKO\logs\_cite_map.json", encoding="utf-8"))
t = open(MD, encoding="utf-8").read()

def C(*ns):
    """把 {n} 占位符替换为真实引用标记"""
    return "".join(f"[[{n}]]({CMAP[str(n)]})" for n in ns)

