# 2) 引言（4 段：立领域 / 综述既往 / 找缺口 / 回填缺口）
# ============================================================
INTRO = """## 引言

骨肉瘤是儿童和青少年中最常见的原发恶性骨肿瘤，具有高致残率与不良预后，其发生发展涉及遗传易感性、表观遗传调控异常及肿瘤微环境重塑等多层次机制{C21}{C22}。尽管采用新辅助化疗联合手术，转移与复发仍是治疗失败的主要原因，而现有预后评估主要依赖临床病理参数（如转移状态、化疗后坏死率），缺乏能够在治疗前稳定识别高危患者的分子工具{C1}。与此同时，骨肉瘤的肿瘤生态系统由恶性成骨谱系细胞、癌相关成纤维细胞、免疫细胞与内皮细胞等异质区室构成，其中驱动细胞外基质重塑与驱动增殖的程序分别由哪些区室承担、二者在下游转录调控层面是否相互独立，迄今尚未被系统解析，细胞外基质重塑轴与免疫调控轴的相对贡献亦不明确{C10}。

既往研究已在多个层面推进了对骨肉瘤分子分型的认识。在bulk转录组层面，研究多依托TARGET等公共队列，通过LASSO-Cox等算法筛选预后相关基因并构建风险模型，已在免疫相关基因、铁代谢相关lncRNA、免疫原性细胞死亡相关基因等维度建立了具有预测价值的signature{C13}{C14}{C15}。单细胞RNA测序（scRNA-seq）技术的引入进一步使研究者在细胞分辨率上解析骨肉瘤的异质性，例如区分恶性与非恶性细胞、比较特定程序在不同细胞类型中的评分差异，以及定位预后基因在成骨细胞谱系、巨噬细胞等特定细胞类型中的表达{C5}{C6}{C7}{C15}{C16}{C17}；基于差异表达与共表达网络的分析亦鉴定出LINC00960、SATB2-AS1等多个候选基因{C8}{C9}。在机制层面，RUNX2等关键转录因子已被多项研究证实参与调控骨肉瘤的增殖、迁移与侵袭，并可作为微小RNA的靶基因介导化疗敏感性{C18}{C19}{C20}，而骨肉瘤中基质细胞与肿瘤细胞之间的相互作用可影响侵袭、炎症反应与血管生成相关基因的表达，免疫逃逸与代谢重编程等特征亦与患者生存差异密切相关{C25}{C26}。

然而，上述研究仍存在明显缺口。其一，多数预后模型受限于单队列训练、缺乏外部独立验证，或未系统校正平台与终点差异，其外部泛化性未获充分检验{C2}{C3}{C4}；其二，基于差异表达与共表达网络的候选基因筛选多停留在基因列表层面，未明确关键基因所归属的细胞区室及其在肿瘤生态系统中的空间分工{C8}{C9}；其三，既往研究多局限于单一组学维度，难以系统阐明候选基因的细胞来源与恶性属性{C21}{C23}{C24}，而现有计算推断所获得的枢纽基因缺乏下游调控程序的机制性解析，难以区分其功能是驱动肿瘤增殖还是塑造免疫抑制微环境，从而限制了靶点优先级的判断{C11}{C12}；其四，将单细胞图谱与预后建模和功能推断相整合的研究仍然有限{C5}{C6}{C7}。更关键的是，尚无研究在单细胞层面以平行虚拟敲除的方式，对分属不同区室的两个枢纽基因开展下游调控程序的对照解析。由此提出本研究的问题：骨肉瘤中是否存在分属不同功能区室、且在下游转录调控层面相互独立的两个枢纽基因？

为回答这一问题，本研究延续"候选筛选—区室定位—网络推断—外部验证"的递进式分析传统，并引入虚拟敲除以补足机制解析环节。研究整合TARGET-OS多队列bulk转录组、五个公共微阵列/RNA-seq队列、单细胞转录组（GSE162454）、体细胞突变数据与ESTIMATE微环境评分，构建以区室解析为主线的整合框架。主要发现有三：一是鉴定出分属增殖区室与基质区室的BUB1与RUNX2两个枢纽基因，其在单细胞层面区室几乎不重叠；二是双基因平行虚拟敲除显示二者下游程序性质不同且无共享失调基因，从转录调控层面支持其正交性；三是基于该候选池构建的14基因EFS风险评分在外部独立队列中保持判别效能，并与低基质/免疫评分、高突变负荷的表型相关。本文按以下结构展开：首先描述候选池构建与枢纽基因鉴定，其次呈现单细胞区室定位与通讯架构，随后报告双基因虚拟敲除的结果，最后给出风险评分的构建与外部验证及其与微环境和突变负荷的关联，并讨论其局限性与转化意义。
"""
INTRO = re.sub(r"\{C(\d+)\}", lambda m: C(int(m.group(1))), INTRO)

m = re.search(r"## 引言\n.*?(?=\n## 材料与方法)", t, flags=re.S)
assert m, "引言节未找到"
t = t[:m.start()] + INTRO + t[m.end():]
print("引言已重写为 4 段")

open(MD, "w", encoding="utf-8").write(t)

