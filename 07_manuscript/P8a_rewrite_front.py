# 1) 摘要（结构化四段，约 495 汉字 ~ 英文 320-340 词）
# ============================================================
ABSTRACT = """## 摘要

**背景与目的**　骨肉瘤是儿童和青少年中最常见的原发恶性骨肿瘤，转移与复发是治疗失败的主要原因。驱动基质重塑与驱动增殖的程序分别归属于哪些细胞区室、二者在下游转录调控层面是否相互独立，迄今尚未被系统解析；现有预后评估亦缺乏在治疗前稳定识别高危患者的分子工具。

**方法**　本研究整合 TARGET-OS bulk 转录组（85 例具可评估无事件生存[EFS]，41 个事件）、五个公共微阵列/RNA-seq 验证队列、单细胞转录组 GSE162454（42,784 个细胞）与 167 个掩码体细胞突变文件，依次开展 limma 差异表达分析、加权基因共表达网络分析（WGCNA）、STRING 蛋白互作网络与 cytoHubba 中心性筛选、单细胞区室定位与 inferCNV 恶性判定、CellChat 细胞通讯分析、scTenifoldKnk 双基因平行虚拟敲除、LASSO-Cox 建模与外部验证，以及 ESTIMATE 微环境评分与肿瘤突变负荷（TMB）关联分析。

**结果**　差异表达与 WGCNA 交集定义了 299 个基因的候选池，并提名分属不同区室的两个核心基因：BUB1（纺锤体组装检查点激酶）与 RUNX2（成骨主转录因子），其 EFS 每标准差风险比（HR）分别为 1.39 与 1.55。RUNX2 富集于癌相关成纤维细胞/间充质干细胞（CAF/MSC，均值 0.921）与成骨细胞（0.804），BUB1 富集于增殖细胞（0.216），二者区室几乎不重叠；inferCNV 将 84.2% 的成骨细胞判为恶性。CellChat 显示 CAF/MSC 发出信号权重最高（8.34），COL1A1-CD44 为最强互作。双基因虚拟敲除分别产生 20 与 17 个失调基因且无共享基因：RUNX2 敲除指向 AP-1/SLRP/TGF-β 基质程序，BUB1 敲除指向髓系-吞噬-补体程序。14 基因 LASSO-Cox 评分在训练队列中 C-index 为 0.796（HR = 5.43，95% CI 3.34-8.84，p = 1.02e-11），在 GSE39055 外部验证中为 0.696（HR = 2.69，p = 0.0342），并与较低的基质评分（rho = -0.55）和较高的 TMB（rho = 0.31）相关。

**结论**　以区室解析为主线的递进式框架鉴定了两个正交枢纽基因，并构建了可外部验证的 EFS 风险评分，为骨肉瘤的风险分层与靶点优先排序提供了候选依据；上述推断尚需蛋白水平与功能实验验证。

### 关键词

骨肉瘤；单细胞转录组；虚拟敲除；细胞区室；预后风险评分
"""

m = re.search(r"## 摘要\n.*?(?=\n## 引言)", t, flags=re.S)
assert m, "摘要节未找到"
t = t[:m.start()] + ABSTRACT + t[m.end():]
print("摘要+关键词已重写")

